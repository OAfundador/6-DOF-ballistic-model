        """Figure 18: downrange distance history."""
        plt = self._pyplot()
        traj, c = self.trajectory, self.palette
        path = self._resolve(save_path, FIGURE_FILENAMES["plot_range_vs_time"])

        fig, ax = plt.subplots(figsize=(14, 8), facecolor=c.bg)
        self._style_axes(ax, "Alcance vs Tempo")

        ax.fill_between(traj.t, 0, traj.x / 1000, alpha=0.15, color=c.secondary)
