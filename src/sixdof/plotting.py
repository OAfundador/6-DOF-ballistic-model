        ax.set_xlabel(_TIME_LABEL, fontsize=12, fontweight="bold")
        ax.set_ylabel(_RANGE_LABEL, fontsize=12, fontweight="bold")
        self._legend(ax)

        self._finish(fig, path)
        return path

